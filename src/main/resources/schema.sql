CREATE TABLE zone (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE commune (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(100) NOT NULL UNIQUE,
    zone_id BIGINT NOT NULL REFERENCES zone(id)
);

CREATE TABLE delivery_window (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id        BIGINT NOT NULL REFERENCES zone(id),
    delivery_date  DATE NOT NULL,
    start_time     TIME NOT NULL,
    end_time       TIME NOT NULL,
    price          INT NOT NULL,
    capacity       INT NOT NULL,
    reserved_count INT NOT NULL DEFAULT 0,
    CONSTRAINT uq_window UNIQUE (zone_id, delivery_date, start_time),
    CONSTRAINT chk_capacity CHECK (reserved_count >= 0 AND reserved_count <= capacity)
);

CREATE TABLE reservation (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_window_id BIGINT NOT NULL REFERENCES delivery_window(id),
    order_reference    VARCHAR(50) NOT NULL UNIQUE,
    address            VARCHAR(255) NOT NULL,
    status             VARCHAR(20) NOT NULL,
    created_at         TIMESTAMP NOT NULL
);